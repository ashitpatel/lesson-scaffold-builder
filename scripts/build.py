"""Generate dist/, the README's "Try it now" links and blog/_data/try_links.yml from prompt/.

Edit only prompt/system-prompt.md and prompt/kickoff.md, then run:

    python3 scripts/build.py          # regenerate dist/ and the README links
    python3 scripts/build.py --check  # fail if any generated file is stale
"""

import argparse
import re
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPT = ROOT / "prompt" / "system-prompt.md"
KICKOFF = ROOT / "prompt" / "kickoff.md"
README = ROOT / "README.md"

# Custom GPT instructions are capped at 8,000 characters.
INSTRUCTIONS_LIMIT = 8000
# The kickoff is pasted as a chat message; stay under the tightest common input box.
KICKOFF_LIMIT = 4000

TRY_START = "<!-- try-links:start (generated by scripts/build.py from prompt/kickoff.md) -->"
TRY_END = "<!-- try-links:end -->"
# Each assistant opens a new chat with the kickoff prompt as the first message.
TRY_LINK_BASES = {
    "ChatGPT": "https://chatgpt.com/?q=",
    "Claude": "https://claude.ai/new?q=",
    "Google AI Mode": "https://www.google.com/search?udm=50&q=",
}


def strip_title(text: str) -> str:
    """Drop the leading H1, which is a file label rather than an instruction."""
    lines = text.splitlines(keepends=True)
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "".join(lines).lstrip("\n")


def check_kickoff(prompt: str, kickoff: str) -> None:
    """Fail if the kickoff is too long or has lost a step of the full prompt."""
    if len(kickoff) > KICKOFF_LIMIT:
        sys.exit(f"error: kickoff is {len(kickoff)} characters; keep it under {KICKOFF_LIMIT}.")
    steps = re.findall(r"\*\*(STEP \d+ — [^*]+?)\*\*", prompt)
    missing = [s for s in steps if f"**{s}**" not in kickoff]
    missing += [p for p in ("evidence-based", "Connected Learning", "participatory budgeting",
                            "teacher card") if p not in kickoff]
    if missing:
        sys.exit(f"error: {KICKOFF.name} is out of sync with {PROMPT.name}; missing: "
                 + "; ".join(missing))


def try_links(kickoff: str) -> dict[str, str]:
    """Each assistant's link that opens a new chat carrying the kickoff prompt."""
    query = urllib.parse.quote(kickoff, safe="")
    return {name: base + query for name, base in TRY_LINK_BASES.items()}


def blog_try_links(links: dict[str, str]) -> str:
    """The same links as Jekyll data, so blog posts can use {{ site.data.try_links.claude }}."""
    lines = ["# Generated by scripts/build.py from prompt/kickoff.md; do not edit."]
    lines += [f'{name.lower().replace(" ", "_")}: "{url}"' for name, url in links.items()]
    return "\n".join(lines) + "\n"


def with_try_links(readme: str, links: dict[str, str]) -> str:
    """Replace the README's "Try it now" links with ones carrying the current kickoff prompt."""
    if TRY_START not in readme or TRY_END not in readme:
        sys.exit(f"error: README.md must contain the markers {TRY_START!r} and {TRY_END!r}")
    links = " · ".join(f"**[Open in {name}]({url})**" for name, url in links.items())
    before, rest = readme.split(TRY_START, 1)
    after = rest.split(TRY_END, 1)[1]
    return f"{before}{TRY_START}\n{links}\n{TRY_END}{after}"


def render() -> dict[str, bytes]:
    prompt = strip_title(PROMPT.read_text(encoding="utf-8"))
    if len(prompt) > INSTRUCTIONS_LIMIT:
        sys.exit(f"error: instructions are {len(prompt)} characters; "
                 f"Custom GPTs accept at most {INSTRUCTIONS_LIMIT}.")
    kickoff = KICKOFF.read_text(encoding="utf-8")
    check_kickoff(prompt, kickoff)
    links = try_links(kickoff)
    return {
        "dist/instructions.md": prompt.encode(),
        "dist/kickoff.md": kickoff.encode(),
        "blog/_data/try_links.yml": blog_try_links(links).encode(),
        "README.md": with_try_links(README.read_text(encoding="utf-8"), links).encode(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = parser.parse_args()

    outputs = render()

    if args.check:
        stale = [p for p, data in outputs.items()
                 if not (ROOT / p).exists() or (ROOT / p).read_bytes() != data]
        if stale:
            print("Generated files are out of date; run python3 scripts/build.py. Stale files:")
            print("\n".join(f"  {p}" for p in stale))
            sys.exit(1)
        print("Generated files are up to date.")
        return

    for path, data in outputs.items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print(f"wrote {path}")
    print(f"instructions: {len(outputs['dist/instructions.md'].decode())} / "
          f"{INSTRUCTIONS_LIMIT} characters")
    print(f"kickoff: {len(outputs['dist/kickoff.md'].decode())} / {KICKOFF_LIMIT} characters")


if __name__ == "__main__":
    main()
